-- Гучність за замовчуванням 70% -> 50%. Хто лишився на 70% (дефолт; база не
-- відрізняє його від вибраних вручну 70%) — переводимо на 50%. DEFAULT 70 у
-- колонці лишається (SQLite не змінює його без перебудови таблиці) — нових
-- користувачів upsertUser створює одразу з 50%.
UPDATE users SET sound_volume = 50 WHERE sound_volume = 70;
